-- ------------------------------------------------------------------------------
-- 3. BẢNG HÀNG ĐỢI (QUEUE), ĐIỀU KHIỂN ĐỒNG BỘ (SYNC CONTROL) & LỊCH SỬ (SYNC LOG)
-- ------------------------------------------------------------------------------
CREATE TABLE C360.C360_SYNC_QUEUE (
    QUEUE_ID        NUMBER GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
    MA_CD           VARCHAR2(30 BYTE) NOT NULL,
    ACTION_TYPE     VARCHAR2(10 BYTE),                      -- 'I', 'U', 'D', 'U_OLD_CD'
    ENQUEUED_AT     TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL
);
CREATE INDEX C360.IDX_QUEUE_ENQUEUED_AT ON C360.C360_SYNC_QUEUE (ENQUEUED_AT, QUEUE_ID);

CREATE TABLE C360.C360_SYNC_CONTROL (
    PIPELINE_NAME       VARCHAR2(50 BYTE) PRIMARY KEY,
    IS_PAUSED_FOR_FULL  NUMBER(1) DEFAULT 0 NOT NULL,       -- 1: Đang yêu cầu dừng Near RT để chạy Full Load
    RUNNING_MODE        VARCHAR2(20 BYTE) DEFAULT 'IDLE',   -- 'IDLE', 'NEAR_RT', 'FULL_LOAD'
    LAST_BATCH_CUT_TIME TIMESTAMP,
    UPDATED_AT          TIMESTAMP DEFAULT SYSTIMESTAMP
);

INSERT INTO C360.C360_SYNC_CONTROL (PIPELINE_NAME, IS_PAUSED_FOR_FULL, RUNNING_MODE)
VALUES ('C360_CITIZEN_PIPELINE', 0, 'IDLE');
COMMIT;

CREATE TABLE C360.C360_SYNC_LOG (
    BATCH_ID            NUMBER GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
    RUN_MODE            VARCHAR2(20 BYTE) NOT NULL,         -- 'FULL_LOAD' / 'NEAR_RT'
    START_TIME          TIMESTAMP NOT NULL,
    END_TIME            TIMESTAMP,
    DISTINCT_MACD_CNT   NUMBER DEFAULT 0,
    MERGED_ROWS         NUMBER DEFAULT 0,
    DELETED_ROWS        NUMBER DEFAULT 0,
    STATUS              VARCHAR2(20 BYTE) NOT NULL,         -- 'RUNNING', 'SUCCESS', 'FAILED'
    ERROR_MESSAGE       VARCHAR2(2000 BYTE)
);

-- ------------------------------------------------------------------------------
-- 4. TRIGGER NHẸ TRÊN BẢNG MIRROR ĐẨY KHÓA MA_CD VÀO QUEUE (Phần 2.5)
-- Lưu ý: Khi UPDATE đổi MA_CD (:OLD.MA_CD <> :NEW.MA_CD), đẩy CẢ mã mới lẫn mã cũ!
-- ------------------------------------------------------------------------------
CREATE OR REPLACE TRIGGER C360.TRG_MIRROR_HGD_CDC_QUEUE
AFTER INSERT OR UPDATE OR DELETE ON C360.MIRROR_VSS_HO_GD_NHANKHAU
FOR EACH ROW
BEGIN
    IF INSERTING THEN
        INSERT INTO C360.C360_SYNC_QUEUE (MA_CD, ACTION_TYPE)
        VALUES (:NEW.MA_CD, 'I');
    ELSIF UPDATING THEN
        INSERT INTO C360.C360_SYNC_QUEUE (MA_CD, ACTION_TYPE)
        VALUES (:NEW.MA_CD, 'U');
        IF :OLD.MA_CD IS NOT NULL AND :OLD.MA_CD <> :NEW.MA_CD THEN
            INSERT INTO C360.C360_SYNC_QUEUE (MA_CD, ACTION_TYPE)
            VALUES (:OLD.MA_CD, 'U_OLD_CD');
        END IF;
    ELSIF DELETING THEN
        INSERT INTO C360.C360_SYNC_QUEUE (MA_CD, ACTION_TYPE)
        VALUES (:OLD.MA_CD, 'D');
    END IF;
END;
/

-- ------------------------------------------------------------------------------
-- 5. BẢNG BẢO MẬT API KEY (SHA-256) & AUDIT LOG TRA CỨU (Phần 3.3)
-- ------------------------------------------------------------------------------
CREATE TABLE C360.C360_API_KEYS (
    KEY_ID          NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    CLIENT_NAME     VARCHAR2(100 BYTE) NOT NULL,
    KEY_HASH_SHA256 VARCHAR2(64 BYTE) NOT NULL UNIQUE,      -- Chỉ lưu SHA-256 hex, không lưu plaintext key
    SCOPES          VARCHAR2(200 BYTE) NOT NULL,            -- VD: 'CA_NHAN:READ,CA_NHAN:BATCH,CA_NHAN:SEARCH,CA_NHAN:DELTA'
    IS_ACTIVE       NUMBER(1) DEFAULT 1 NOT NULL,
    CREATED_AT      TIMESTAMP DEFAULT SYSTIMESTAMP
);

CREATE TABLE C360.C360_API_AUDIT_LOG (
    LOG_ID          NUMBER GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
    CLIENT_NAME     VARCHAR2(100 BYTE),
    ENDPOINT        VARCHAR2(200 BYTE),
    QUERY_PARAMS    VARCHAR2(1000 BYTE),
    HTTP_STATUS     NUMBER(3),
    RESPONSE_MS     NUMBER(10,2),
    REQUESTED_AT    TIMESTAMP DEFAULT SYSTIMESTAMP
);
