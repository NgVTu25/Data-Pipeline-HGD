-- ------------------------------------------------------------------------------
-- 1. VIEW DANH MỤC ĐỊA BÀN ĐANG HIỆU LỰC & 2 BẢNG MAP TRA CỨU PHẲNG (TỈNH / XÃ)
-- ------------------------------------------------------------------------------
CREATE OR REPLACE VIEW C360.VW_DM_DBHC_ACTIVE AS
SELECT
    TRIM(MA_DBHC)    AS MA_DBHC,
    TRIM(MA_CHA)     AS MA_CHA,
    TRIM(TEN)        AS TEN,
    TRIM(MA_DBHC_SN) AS MA_DBHC_SN
FROM C360.MIRROR_VSS_DM_DBHC
WHERE TINH_TRANG = '1'
  AND STATUS = '1'
  AND (NGAY_HET_HIEU_LUC IS NULL OR NGAY_HET_HIEU_LUC > SYSTIMESTAMP);

-- Bảng Map Tỉnh phẳng (đã tách chuỗi MA_DBHC_SN, chuẩn hóa mọi biến thể đầu vào)
CREATE TABLE C360.C360_MAP_DBHC_TINH (
    MA_INPUT        VARCHAR2(10 BYTE) NOT NULL PRIMARY KEY, -- VD: '01TTT', '001', '01', '1', '34TTT', '34'
    MA_TINH_MOI     VARCHAR2(3 BYTE),                       -- Chuẩn 3 số: '001', '033', '079'
    MA_DBHC_GOC     VARCHAR2(5 BYTE),                       -- '01TTT', '33TTT'
    TEN_TINH_MOI    VARCHAR2(200 BYTE),
    NGUON_MAP       VARCHAR2(20 BYTE) NOT NULL,             -- 'HIEN_HANH', 'SAP_NHAP', 'MO_HO'
    UPDATED_AT      TIMESTAMP DEFAULT SYSTIMESTAMP
);

-- Bảng Map Xã phẳng (đã tách chuỗi MA_DBHC_SN, gồm cả biến thể mất số 0 đầu)
CREATE TABLE C360.C360_MAP_DBHC_XA (
    MA_INPUT        VARCHAR2(10 BYTE) NOT NULL PRIMARY KEY, -- VD: '00004', '4', '00013', '13'
    MA_XA_MOI       VARCHAR2(5 BYTE),                       -- NULL nếu NGUON_MAP = 'MO_HO'
    TEN_XA_MOI      VARCHAR2(200 BYTE),
    MA_TINH_MOI     VARCHAR2(3 BYTE),                       -- Suy ra từ MA_CHA của xã mới (giữ được nếu cùng tỉnh)
    TEN_TINH_MOI    VARCHAR2(200 BYTE),
    NGUON_MAP       VARCHAR2(20 BYTE) NOT NULL,             -- 'HIEN_HANH', 'SAP_NHAP', 'MO_HO'
    SO_XA_MOI       NUMBER(5) DEFAULT 1,
    UPDATED_AT      TIMESTAMP DEFAULT SYSTIMESTAMP
);

